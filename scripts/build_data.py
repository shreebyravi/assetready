"""Bundle data/, policies/ and recorded runs into app/data.js so index.html works when double-clicked.
Run: python scripts/build_data.py"""
import csv, glob, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rows(name):
    with open(os.path.join(ROOT, "data", name), encoding="utf-8") as f:
        return list(csv.DictReader(f))


def texts(pattern):
    out = {}
    for p in sorted(glob.glob(os.path.join(ROOT, pattern))):
        with open(p, encoding="utf-8") as f:
            out[os.path.splitext(os.path.basename(p))[0]] = f.read()
    return out


def jsons(pattern):
    out = {}
    for p in sorted(glob.glob(os.path.join(ROOT, pattern))):
        with open(p, encoding="utf-8") as f:
            out[os.path.splitext(os.path.basename(p))[0]] = json.load(f)
    return out


def runs():
    out = {}
    for p in sorted(glob.glob(os.path.join(ROOT, "data", "recorded", "runs", "*.jsonl"))):
        events = []
        with open(p, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    events.append(json.loads(line))
        out[os.path.splitext(os.path.basename(p))[0]] = events
    return out


meta_path = os.path.join(ROOT, "data", "recorded", "meta.json")
meta = json.load(open(meta_path, encoding="utf-8")) if os.path.exists(meta_path) else {}

data = {
    "construction_register": rows("construction_register.csv"),
    "equipment_schedule": rows("equipment_schedule.csv"),
    "fm_register": rows("fm_register.csv"),
    "ground_truth": rows("ground_truth.csv"),
    "eval_cases": rows("eval_cases.csv"),
    "documents": texts("data/documents/*.md"),
    "policies": texts("policies/*.md"),
    "stress": jsons("data/stress/*.json"),
    "recorded": runs(),
    "recorded_meta": meta,
}
js = "/* Generated by scripts/build_data.py. Do not edit by hand. All data is synthetic. */\n"
js += "var AR_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
js += "if (typeof module !== 'undefined' && module.exports) module.exports = AR_DATA;\n"
open(os.path.join(ROOT, "app", "data.js"), "w", encoding="utf-8").write(js)
print("app/data.js:", len(data["construction_register"]), "assets,", len(data["documents"]), "documents,", len(data["recorded"]), "recorded runs")
